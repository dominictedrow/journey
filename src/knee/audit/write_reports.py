def _q(s: pd.Series, qs=(0, 0.05, 0.25, 0.5, 0.75, 0.95, 1)) -> str:
    s = pd.to_numeric(s, errors="coerce").dropna()
    if s.empty:
        return "n/a"
    return " / ".join(f"{v:.4g}" for v in s.quantile(list(qs)))


def _table(df: pd.DataFrame) -> str:
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join("" if pd.isna(v) else (f"{v:.4g}" if isinstance(v, float) else str(v)) for v in r) + " |")
    return "\n".join(lines)


def _vc(s: pd.Series, top: int = 15) -> str:
    vc = s.fillna("(missing)").astype(str).value_counts()
    rows = [(k, int(v), f"{100 * v / len(s):.1f}%") for k, v in vc.head(top).items()]
    out = _table(pd.DataFrame(rows, columns=["value", "count", "%"]))
    return out + (f"\n\n_{len(vc) - top} more values not shown._" if len(vc) > top else "")


